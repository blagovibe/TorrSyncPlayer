/**
 * @file backendargs.h
 * @brief Аргументы командной строки для встроенного Go-бэкенда
 *
 * Вынесено отдельной единицей по конкретной причине. Фронтенд запускает
 * бэкенд процессом и передаёт ему флаги. Бэкенд разбирает их через
 * `flag.Parse`, а неизвестный флаг — это не предупреждение, а
 * `flag provided but not defined` и `os.Exit(2)`: приложение просто не
 * стартует, и ни один тест этого не замечает, потому что `main.cpp` не
 * собирается ни в один тестовый таргет.
 *
 * Именно так в релиз Windows уехал `--jwt-secret` — флага, который удалили
 * вместе с JWT-аутентификацией (backend commit 2433caf), а во фронтенде он
 * остался. Релизный бинарь не запускался, все 14 джоб CI были зелёными.
 *
 * Здесь же живут токен и порт запуска, потому что оба — значения флагов
 * этого же бэкенда, и оба должны вычисляться в тестируемом коде: `main.cpp`
 * ни в один тестовый таргет не входит.
 *
 * Контракт, который держит `test_backendargs.cpp`: каждый флаг отсюда обязан
 * существовать в `parseFlags` (`backend/cmd/server/main.go`).
 */

#ifndef BACKENDARGS_H
#define BACKENDARGS_H

#include <QtCore/QUrl>
#include <QtCore/QString>
#include <QtCore/QStringList>
#include <QtNetwork/QTcpServer>

namespace BackendArgs {

/**
 * @brief Флаги, которые бэкенд понимает на старте.
 *
 * Держится здесь, а не читается из main.go, чтобы тест мог сверить список с
 * фактическим набором аргументов. При добавлении флага в Go нужно добавить
 * его и сюда — иначе сборка теста упадёт, что и требуется.
 */
const QStringList &knownBackendFlags();

/**
 * @brief Сгенерировать токен доступа для встроенного бэкенда.
 *
 * Токен принадлежит клиенту, а не бэкенду. Если токен не задан, бэкенд
 * генерирует случайный и печатает его в stdout — а клиент этот stdout видит
 * только в отладочном выводе и никогда его не читает, поэтому остаётся без
 * доступа к собственному бэкенду (bug-0060). Секрет, который выдаёт
 * родительский процесс, — это ровно тот режим, который `--token` описан как
 * основной: «тот, кто его задал, знает его и так».
 *
 * @return hex-строка фиксированной длины
 */
QString generateToken();

/**
 * @brief Каталоги, в которых ищется готовый бэкенд, если он не встроен
 *
 * Существует по той же причине, что и весь этот модуль: поиск жил в
 * `main.cpp`, который не входит ни в один тестовый таргет, и поэтому
 * перечислял только `*.exe`. На Linux и macOS ни одно имя не совпадало, и
 * приложение стартовало без торрент-клиента (bug-0066) — молча, потому что
 * qWarning в этом месте никто не слушал.
 *
 * Имена без расширения обязательны: сборка называет бинарник по-разному на
 * разных платформах, и список проверок не должен зависеть от Windows.
 *
 * @param appDir каталог исполняемого файла приложения
 */
QStringList candidateBackendPaths(const QString &appDir);

/**
 * @brief Подобрать свободный TCP-порт для встроенного бэкенда.
 *
 * Каждый экземпляр приложения поднимает свой бэкенд, поэтому фиксированный
 * порт означал бы, что второй экземпляр на той же машине не может занять
 * свой собственный и молча начинает работать с чужим сервером.
 *
 * @return свободный порт, либо 0 если подобрать не удалось
 */
quint16 pickFreePort();

/**
 * @brief Собрать аргументы для запуска встроенного бэкенда
 * @param port Порт, на котором бэкенд должен слушать
 * @param token Токен доступа; если пусто, бэкенд сгенерирует свой
 * @return Список аргументов, готовый для QProcess::setArguments
 */
QStringList build(const QString &port, const QString &token);

} // namespace BackendArgs

#endif // BACKENDARGS_H